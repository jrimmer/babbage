#!/usr/bin/env python3
"""Writes crates/babbage-core/src/chinese_new_year.rs: the day of each Chinese New Year, 1900 to 2099.

The dates come from the lunardate package (a table of the lunar calendar), as the number of days after
21 January, which is the earliest the festival ever falls. Run it from the repository root with the oracle
virtual environment: .oracle-venv/bin/python tools/gen_lunar_data.py
"""
import subprocess
import warnings
from datetime import date

from lunardate import LunarDate

warnings.simplefilter("ignore")

FIRST, LAST = 1900, 2099
offsets = []
for year in range(FIRST, LAST + 1):
    new_year = LunarDate(year, 1, 1).to_solar_date()
    assert new_year.year == year
    offsets.append((new_year - date(year, 1, 21)).days)
assert min(offsets) == 0 and max(offsets) <= 30, (min(offsets), max(offsets))

rows = ",".join(str(o) for o in offsets)
text = f"""//! Chinese New Year for 1900 to 2099, generated by tools/gen_lunar_data.py from the lunardate package.
//! Each entry is the number of days after 21 January, the earliest the festival falls.

pub const FIRST_YEAR: i64 = {FIRST};

pub const DAYS_AFTER_JANUARY_21: [u8; {len(offsets)}] = [{rows}];
"""
path = "crates/babbage-core/src/chinese_new_year.rs"
open(path, "w").write(text)
subprocess.run(["rustfmt", "--edition", "2024", path], check=True)
print(len(offsets), "years written")
