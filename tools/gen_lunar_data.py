#!/usr/bin/env python3
"""Writes crates/babbage-core/src/chinese_new_year.rs: the day of each Chinese New Year, 1900 to 2299.

1900 to 2099 come from the lunardate package (a table of the lunar calendar). 2100 onward is computed from the
sky: the new year is the start of the month after the one holding the December solstice (second new moon after
it, the third when a leap month 11 or 12 intervenes), in China Standard Time. That method agrees with the
lunardate table in 199 of its 200 years (the exception, 1916, is a historical time-zone quirk), and gives
9 February 2100, as expected. Each entry is the number of days after 21 January, the earliest
the festival falls.

Run from the repository root: .oracle-venv/bin/python tools/gen_lunar_data.py  (the years from 2100 need the
ephem package too: pip install ephem into the same environment).
"""
import math
import datetime
import subprocess
import warnings
from datetime import date

import ephem
from lunardate import LunarDate

warnings.simplefilter("ignore")

FIRST, LAST_TABLE, LAST = 1900, 2099, 2299

def sun_lon(d):
    s = ephem.Sun(d)
    return math.degrees(ephem.Ecliptic(s, epoch=d).lon) % 360

def cst_day(d):
    dt = ephem.Date(d).datetime() + datetime.timedelta(hours=8)
    return dt.date()

def new_moons(start, end):
    out = []
    d = ephem.next_new_moon(ephem.Date(start))
    while d < ephem.Date(end):
        out.append(cst_day(d)); d = ephem.next_new_moon(d + 1)
    return out

def term_day(year, k):
    """CST day of the moment the sun reaches longitude 30*k, searched around its usual date."""
    target = 30 * k
    guess = ephem.Date(f"{year}/3/20") + (target / 360) * 365.2422
    lo, hi = guess - 20, guess + 20
    def diff(d):
        return ((sun_lon(d) - target + 180) % 360) - 180
    for _ in range(50):
        mid = (lo + hi) / 2
        if diff(mid) < 0: lo = mid
        else: hi = mid
    return cst_day((lo + hi) / 2)

def zhongqi(first_year, last_year):
    days = []
    for y in range(first_year, last_year + 1):
        for k in range(12):
            days.append(term_day(y, k))
    return sorted(set(days))

def new_year(year):
    nm = new_moons(f"{year-1}/11/1", f"{year+1}/3/1")
    zq = zhongqi(year - 1, year + 1)
    sol_prev = term_day(year - 1, 9)  # 270 degrees, December solstice
    sol_this = term_day(year, 9)
    # month 11 begins on the last new moon on or before the earlier solstice
    i11 = max(i for i, d in enumerate(nm) if d <= sol_prev)
    j11 = max(i for i, d in enumerate(nm) if d <= sol_this)
    months = j11 - i11
    assert months in (12, 13), (year, months)
    idx = 2
    if months == 13:
        for i in range(i11 + 1, j11):
            nxt = nm[i + 1]
            if not any(nm[i] <= z < nxt for z in zq):
                leap = i - i11
                if leap <= 2:
                    idx = 3
                break
    return nm[i11 + idx]


offsets = []
for year in range(FIRST, LAST + 1):
    new_year_day = (
        LunarDate(year, 1, 1).to_solar_date() if year <= LAST_TABLE else new_year(year)
    )
    assert new_year_day.year == year
    offsets.append((new_year_day - date(year, 1, 21)).days)
assert min(offsets) == 0 and max(offsets) <= 30, (min(offsets), max(offsets))

rows = ",".join(str(o) for o in offsets)
text = f"""//! Chinese New Year for {FIRST} to {LAST}, generated by tools/gen_lunar_data.py: the lunardate package up to
//! {LAST_TABLE} and the sky after it. Each entry is the number of days after 21 January, the earliest the
//! festival falls.

pub const FIRST_YEAR: i64 = {FIRST};

pub const DAYS_AFTER_JANUARY_21: [u8; {len(offsets)}] = [{rows}];
"""
path = "crates/babbage-core/src/chinese_new_year.rs"
open(path, "w").write(text)
subprocess.run(["rustfmt", "--edition", "2024", path], check=True)
print(len(offsets), "years written")
